function copyRepo(root) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'orunmila-mutants-'));
  fs.cpSync(root, dir, { recursive: true, filter: (src) => !SKIP.has(path.basename(src)) || src === root });
  return dir;
}

